/**
 * 체크박스를 만드는 입력 규칙.
 *
 * `[] ` 와 `[ ] ` 둘 다 받는다. 같은 기호이고 사이를 띄우느냐만 다르다 —
 * 마크다운에서 할 일을 `- [ ]` 로 쓰기 때문에 띄어 치는 손버릇이 흔하고,
 * 안내에 적을 때도 `[ ]` 쪽이 대괄호 두 개로 읽힌다. 붙여 친 사람을
 * 실패시킬 이유가 없다.
 *
 * 하이픈은 하이픈으로 남긴다. 줄 앞에 - 를 찍는 것은 항목을 나열하는 아주
 * 흔한 손버릇이라, 칠 때마다 체크박스가 되면 성가시다.
 */
export const TASK_INPUT_RULE = /^\[ ?\]\s$/
