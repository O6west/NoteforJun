/**
 * 체크박스를 만드는 입력 규칙.
 *
 * `[] ` 와 `[ ] ` 둘 다 받는다. 같은 기호이고 사이를 띄우느냐만 다르다 —
 * 마크다운에서 할 일을 `- [ ]` 로 쓰기 때문에 띄어 치는 손버릇이 흔하고,
 * 안내에 적을 때도 `[ ]` 쪽이 대괄호 두 개로 읽힌다. 붙여 친 사람을
 * 실패시킬 이유가 없다.
 *
 * 하이픈은 하이픈으로 남긴다. 줄 앞에 - 를 찍는 것은 항목을 나열하는 아주
 * 흔한 손버릇이라, 칠 때마다 체크박스가 되면 성가시다.
 */
export const TASK_INPUT_RULE = /^\[ ?\]\s$/

/**
 * `->` 를 `→` 로 바꾸는 입력 규칙.
 *
 * 이 앱만의 약속이 아니라서 넣었다. 워드에서도 슬랙에서도 노션에서도 같은
 * 일이 일어나므로 배울 것이 없다 — 치던 대로 치면 원하던 것이 나온다.
 *
 * `-` 하나는 그대로 둔다(TASK_INPUT_RULE 설명 참고). 화살표는 `>` 까지
 * 쳤을 때만 만들어지므로, 항목을 나열하려고 찍은 `- ` 와 부딪히지 않는다.
 *
 * 줄 어디에서나 반응한다. 화살표는 문장 가운데에 쓰는 기호다.
 *
 * 되돌리려면 Backspace 한 번. TipTap이 입력 규칙 직후의 Backspace를
 * undoInputRule로 받아 `->` 를 되살려 준다 — `->` 를 글자 그대로 남겨야
 * 하는 사람에게도 길이 있다.
 */
export const ARROW_INPUT_RULE = /->$/
